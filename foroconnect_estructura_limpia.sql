-- Ejecutar en una base/esquema sin estas tablas; NO ejecutar sobre la BD actual.
-- Orden de creacion: USUARIOS, CATEGORIAS, PUBLICACIONES, COMENTARIOS.
-- Este archivo solo crea la estructura. No contiene los registros de prueba.

CREATE TABLE USUARIOS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONTRASENA VARCHAR2(255 CHAR) NOT NULL,
    CORREO VARCHAR2(255 CHAR) NOT NULL,
    NOMBRE VARCHAR2(255 CHAR) NOT NULL,
    ROL VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_CORREO UNIQUE (CORREO)
);

CREATE TABLE CATEGORIAS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    DESCRIPCION VARCHAR2(500 CHAR),
    NOMBRE VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID),
    CONSTRAINT UK_CATEGORIAS_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE PUBLICACIONES (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONTENIDO VARCHAR2(4000 CHAR) NOT NULL,
    FECHA_CREACION TIMESTAMP(9) NOT NULL,
    TITULO VARCHAR2(255 CHAR) NOT NULL,
    USUARIO_ID NUMBER(19,0) NOT NULL,
    CATEGORIA_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_PUBLICACIONES PRIMARY KEY (ID),
    CONSTRAINT FK_PUBLICACIONES_CATEGORIAS FOREIGN KEY (CATEGORIA_ID)
        REFERENCES CATEGORIAS (ID)
);

CREATE TABLE COMENTARIOS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONTENIDO VARCHAR2(2000 CHAR) NOT NULL,
    FECHA_CREACION TIMESTAMP(9) NOT NULL,
    USUARIO_ID NUMBER(19,0) NOT NULL,
    PUBLICACION_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_COMENTARIOS PRIMARY KEY (ID),
    CONSTRAINT FK_COMENTARIOS_PUBLICACIONES FOREIGN KEY (PUBLICACION_ID)
        REFERENCES PUBLICACIONES (ID)
);
